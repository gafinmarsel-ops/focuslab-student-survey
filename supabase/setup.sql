-- FocusLab database setup
-- Run this script in the Supabase SQL Editor.
-- Anonymous visitors can submit responses but cannot read individual rows.

create table if not exists public.survey_responses (
    id bigint generated by default as identity primary key,
    answers jsonb not null,
    created_at timestamptz not null default now()
);

alter table public.survey_responses enable row level security;

-- Remove public/anonymous SELECT policies left by earlier app versions.
do $$
declare
    policy_record record;
begin
    for policy_record in
        select policyname
        from pg_policies
        where schemaname = 'public'
          and tablename = 'survey_responses'
          and cmd = 'SELECT'
          and ('anon' = any(roles) or 'public' = any(roles))
    loop
        execute format(
            'drop policy if exists %I on public.survey_responses',
            policy_record.policyname
        );
    end loop;
end
$$;

drop policy if exists "Allow anonymous survey submissions"
    on public.survey_responses;

create policy "Allow anonymous survey submissions"
    on public.survey_responses
    for insert
    to anon
    with check (jsonb_typeof(answers) = 'object');

-- No public SELECT policy is created. The dashboard uses this aggregate-only
-- function and suppresses analytics until at least five responses exist.
create or replace function public.get_survey_stats()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    with source_rows as (
        select answers
        from public.survey_responses
        where answers is not null
          and jsonb_typeof(answers) = 'object'
    ),
    normalized as (
        select
            coalesce(
                answers ->> 'notification_distraction',
                answers ->> 'Отвлекают уведомления'
            ) as notification_frequency,
            coalesce(
                answers ->> 'daily_phone_time',
                answers ->> 'Время в смартфоне'
            ) as phone_time,
            coalesce(
                answers ->> 'focus_score',
                answers ->> 'Концентрация (1–10)'
            ) as focus_text,
            coalesce(
                answers ->> 'age',
                answers ->> 'Возраст'
            ) as age_text
        from source_rows
    ),
    summary as (
        select
            count(*) as total_responses,
            case when count(*) >= 5 then round(avg(
                case
                    when focus_text ~ '^[0-9]+([.][0-9]+)?$'
                    then focus_text::numeric
                end
            ), 1) else null end as average_focus_score,
            case when count(*) >= 5 then round(avg(
                case
                    when age_text ~ '^[0-9]+([.][0-9]+)?$'
                    then age_text::numeric
                end
            ), 1) else null end as average_age
        from normalized
    ),
    notification_totals as (
        select coalesce(
            jsonb_object_agg(notification_frequency, response_count),
            '{}'::jsonb
        ) as values
        from (
            select notification_frequency, count(*) as response_count
            from normalized
            where notification_frequency is not null
            group by notification_frequency
            having count(*) >= 5
        ) counts
    ),
    phone_time_totals as (
        select coalesce(
            jsonb_object_agg(phone_time, response_count),
            '{}'::jsonb
        ) as values
        from (
            select phone_time, count(*) as response_count
            from normalized
            where phone_time is not null
            group by phone_time
            having count(*) >= 5
        ) counts
    )
    select jsonb_build_object(
        'total_responses', summary.total_responses,
        'average_focus_score', summary.average_focus_score,
        'average_age', summary.average_age,
        'notification_counts', notification_totals.values,
        'phone_time_counts', phone_time_totals.values
    )
    from summary
    cross join notification_totals
    cross join phone_time_totals;
$$;

revoke all on function public.get_survey_stats() from public;
grant execute on function public.get_survey_stats() to anon, authenticated;
